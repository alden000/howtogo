#!/usr/bin/env node
// M6 W-A: writes src/android-pictures.ts from Creative's drawn pictures (creative/m6/pictures, STYLE-GUIDE
// 6h.9) so the /android page can INLINE them (they follow dark mode through the ig-* token classes).
// The per-file <style> block (identical in every picture) is lifted out once as PICTURE_STYLE, and the
// xmlns attribute is dropped (inline SVG in HTML needs none). Re-run after Creative changes a picture:
//   node scripts/embed-android-pictures.mjs
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = [
  "install-1-warn", "install-2-open", "install-3-source", "install-4-install",
  "install-5-protect", "install-6-done", "update-1", "perm-location",
];
const dir = new URL("../../../creative/m6/pictures/", import.meta.url);
let style = null;
const pictures = {};
for (const name of NAMES) {
  pictures[name] = {};
  for (const lang of ["zh", "en"]) {
    let svg = readFileSync(new URL(`${name}-${lang}.svg`, dir), "utf8").trim();
    const m = /<style>([\s\S]*?)<\/style>\s*/.exec(svg);
    if (!m) throw new Error(`${name}-${lang}: no <style>`);
    if (style !== null && style !== m[1]) throw new Error(`${name}-${lang}: <style> differs from the others`);
    style = m[1];
    svg = svg.replace(m[0], "").replace(/\s+xmlns="[^"]*"/, "").replace(/\r/g, "");
    if (/<script|href=|https?:\/\//i.test(svg)) throw new Error(`${name}-${lang}: unexpected script or link`);
    pictures[name][lang] = svg;
  }
}
const out =
  "// GENERATED by scripts/embed-android-pictures.mjs from creative/m6/pictures — do not edit by hand.\n" +
  `export const PICTURE_STYLE = ${JSON.stringify(style)};\n` +
  `export type PictureName = ${NAMES.map((n) => JSON.stringify(n)).join(" | ")};\n` +
  `export const PICTURES: Record<PictureName, { zh: string; en: string }> = ${JSON.stringify(pictures, null, 1)};\n`;
writeFileSync(new URL("../src/android-pictures.ts", import.meta.url), out);
console.log(`embed-android-pictures: ${NAMES.length * 2} pictures written to src/android-pictures.ts`);
