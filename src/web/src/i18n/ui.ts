export type UiKey = keyof typeof zh;
export const UI: Record<UiLang, Record<UiKey, string>> = { zh, en };
export const tr = (lang: UiLang, key: UiKey): string => UI[lang][key];
/** Translate and fill `{name}` placeholders. */
export const tf = (lang: UiLang, key: UiKey, params: Record<string, string | number> = {}): string =>
  UI[lang][key].replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
